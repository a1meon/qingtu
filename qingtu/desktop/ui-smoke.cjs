const {app}=require('electron');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
const {start}=require(process.env.QINGTU_TEST_APP_ROOT?path.join(process.env.QINGTU_TEST_APP_ROOT,'desktop/main.cjs'):'./main.cjs');
const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
async function waitFor(win,expr){for(let n=0;n<160;n++){if(await win.webContents.executeJavaScript(expr))return;await pause(100);}throw new Error('Timed out: '+expr);}
(async()=>{
 const temp=await fs.mkdtemp(path.join(os.tmpdir(),'qingtu-ui-'));
 try{
  const {win,service}=await start({testFolder:temp,testFiles:[path.join(__dirname,'../public/samples/alpine-lake.jpg')],hidden:true});
  win.webContents.setBackgroundThrottling(false);
  win.show();win.focus();
  const js=expr=>win.webContents.executeJavaScript(expr);
  await waitFor(win,"!!document.querySelector('#width')");
  assert.equal(await js("document.querySelector('#width').value"),'3840','empty dimensions use 4K');
  assert.equal(await js("document.querySelector('#height').value"),'2160');
  assert.equal(await js("document.querySelector('#format').textContent"),'PNG');
  assert.equal(await js("document.querySelectorAll('.film-select').length"),0);
  await fs.mkdir(path.join(__dirname,'../artifacts'),{recursive:true});
  await js("Promise.all(Array.from(document.images,img=>img.decode()))");
  await pause(400);
  await fs.writeFile(path.join(__dirname,'../artifacts/native-blue-expanded.png'),(await win.webContents.capturePage()).toPNG());
  await js("document.querySelector('[aria-label=\"收起导出设置\"]').click()");
  await pause(400);
  await fs.writeFile(path.join(__dirname,'../artifacts/native-blue-collapsed.png'),(await win.webContents.capturePage()).toPNG());
  await js("document.querySelector('[aria-label=\"展开导出设置\"]').click()");
  await pause(400);
  assert.equal(await js("document.querySelector('.tool-nav').innerText.trim()"),'','navigation has no permanent text');
  await js("document.querySelector('[aria-label=\"压缩调整\"]').dispatchEvent(new MouseEvent('mouseover',{bubbles:true}))");
  await waitFor(win,"document.querySelector('[role=tooltip]')?.textContent==='压缩调整'");
  await js("document.querySelector('[aria-label=\"压缩调整\"]').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))");
  assert.equal(await js("!!document.querySelector('[role=tooltip]')"),false);
  app.focus({steal:true});win.focus();
  await waitFor(win,"document.hasFocus()");
  await js("document.querySelector('[aria-label=\"图像拼接\"]').focus()");
  await waitFor(win,"document.querySelector('[role=tooltip]')?.textContent==='图像拼接 · 开发中'");
  assert.equal(await js("document.querySelector('[aria-label=\"图像拼接\"]').getAttribute('aria-disabled')"),'true');
  await js("document.querySelector('[aria-label=\"图像拼接\"]').click(); document.querySelector('[aria-label=\"收起导出设置\"]').click()");
  await pause(400);
  assert.equal(await js("document.querySelector('.inspector-shell').getBoundingClientRect().width"),0);
  assert.equal(await js("document.querySelector('.inspector').inert"),true,'hidden fields cannot receive keyboard focus');
  assert.equal(await js("document.querySelector('.stage').getBoundingClientRect().right >= innerWidth-1"),true);
  await js("document.querySelector('[aria-label=\"展开导出设置\"]').click()");
  await pause(400);
  assert.equal(await js("document.querySelector('#format').textContent"),'PNG');
  win.webContents.debugger.attach('1.3');
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]});
  assert.equal(await js("getComputedStyle(document.querySelector('.workspace')).transitionDuration"),'0s','reduced motion removes sidebar animation');
  assert.equal(await js("getComputedStyle(document.querySelector('.film-item')).animationName"),'none');
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia',{features:[]});
  win.webContents.debugger.detach();
  await js("document.querySelector('.add-tile').click()");
  await waitFor(win,"document.querySelector('.processed-label')?.textContent.startsWith('处理后')");
  assert.equal(await js("document.querySelector('.preview-status').textContent.startsWith('PNG')"),true,'default format reaches the real encoder');
  const before=await js("document.querySelector('.compare-image').src");
  const tokens=[...service.results.keys()];
  const split=await js("document.querySelector('.comparator').getAttribute('style')");
  await js("document.querySelector('[aria-label=\"收起导出设置\"]').click()");
  await pause(550);
  await js("document.querySelector('[aria-label=\"展开导出设置\"]').click()");
  await pause(550);
  assert.equal(await js("document.querySelector('.compare-image').src"),before,'sidebar toggle retains the decoded output');
  assert.equal(await js("document.querySelector('.comparator').getAttribute('style')"),split);
  assert.deepEqual([...service.results.keys()],tokens,'sidebar toggle does not start a new encoding job');
  await js("document.querySelector('.export-button').click()");
  await waitFor(win,"document.querySelector('.notice')?.textContent.includes('已导出 1 张')");
  const saved=path.join(temp,(await fs.readdir(temp))[0]);
  const sharp=(await import('sharp')).default;
  assert.equal((await sharp(saved).metadata()).format,'png');
  assert.ok((await fs.stat(saved)).size<=10000000);
  assert.equal([...service.results.values()][0].output.limitBytes,10000000,'10 MB uses decimal filesystem bytes');
  assert.equal([...service.results.values()][0].output.paddedBytes,0);
  await js("document.querySelector('[aria-label=\"清空图片\"]').click(); document.querySelector('[aria-label=\"重置设置\"]').click()");
  await waitFor(win,"document.querySelectorAll('.film-select').length===0");
  assert.equal(await js("document.querySelector('#width').value"),'3840');
  assert.equal(await js("document.querySelector('#height').value"),'2160');
  assert.equal(await js("document.querySelector('#format').textContent"),'PNG');
  await fs.mkdir(path.join(__dirname,'../artifacts'),{recursive:true});
  await fs.writeFile(path.join(__dirname,'../artifacts/ui-smoke.json'),JSON.stringify({passed:true,empty4K:true,defaultPngExport:true,hoverAndFocusLabels:true,hiddenControlsInert:true,sidebarRetainsOutput:true,sidebarDoesNotReencode:true,reservedStitching:true,reducedMotion:true},null,2));
  console.log('UI smoke passed: 4K empty state, PNG export, tooltip, reserved tool, sidebar state retained');
  win.destroy();app.quit();
 }finally{await fs.rm(temp,{recursive:true,force:true});}
})().catch(error=>{console.error(error);app.exit(1);});
